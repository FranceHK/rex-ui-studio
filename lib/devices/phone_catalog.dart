/// Android dp kutoka density RASMI ya profile ya Android SDK (si PPI).
Size _dp(Size px, int dpi) => Size(
  (px.width * 160 / dpi).floorToDouble(),
  (px.height * 160 / dpi).floorToDouble(),
);

/// Makisio ya dp kwa vifaa visivyo na profile rasmi: tunatumia density za
/// marejeo za Android SDK (xhdpi 320 kwa 720px, 420dpi kwa 1080px,
/// 560dpi kwa 1440px). Haya si maadili rasmi ya mtengenezaji.
int _referenceDpi(Size px) {
  final w = px.shortestSide;
  if (w <= 800) return 320;
  if (w >= 1400 && w < 1600) return 560;
  return 420;
}

DeviceDisplay _android({
  DisplayRole role = DisplayRole.main,
  required Size px,
  double? inch,
  double? ppi,
  String? refresh,
  String? type,
  int? sdkDpi,
  String? sdkProfile,
  int? estimateDpi,
  List<DisplayCutout> cutouts = const [],
  Set<String> unverified = const {},
}) {
  final verifiedLogical = sdkDpi != null;
  final dpi = sdkDpi ?? estimateDpi ?? _referenceDpi(px);
  return DeviceDisplay(
    role: role,
    physical: px,
    diagonal: inch,
    ppi: ppi,
    refresh: refresh,
    type: type,
    logical: verifiedLogical ? _dp(px, dpi) : null,
    estimatedLogical: verifiedLogical ? null : _dp(px, dpi),
    scale: verifiedLogical ? dpi / 160 : null,
    densityDpi: verifiedLogical ? dpi : null,
    logicalSource: verifiedLogical
        ? 'Android SDK device profile "$sdkProfile" ($dpi dpi)'
        : 'Makisio: density ya marejeo $dpi dpi (haijathibitishwa)',
    safeArea: _androidSafe,
    cutouts: cutouts,
    unverified: {
      'safeArea',
      if (!verifiedLogical) 'logical',
      if (refresh == null) 'refresh',
      if (type == null) 'type',
      if (ppi == null) 'ppi',
      ...unverified,
    },
  );
}

