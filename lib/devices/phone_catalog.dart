/// nje haina profile yake, kwa hiyo dp yake ni makisio kwa density ileile.
DevicePreset _pixelFold(
  String id,
  String family,
  String model,
  int year, {
  required String sdk,
  required int dpi,
  required (Size, double, double, String?) inner,
  required (Size, double, double, String?) outer,
}) {
  return DevicePreset(
    id: id,
    manufacturer: Manufacturer.google,
    family: family,
    model: model,
    releaseYear: year,
    sourceUrl: _pixelSpecs,
    status: VerificationStatus.partial,
    notes: [
      'Skrini ya ndani: dp kutoka profile ya Android SDK "$sdk" ($dpi dpi). '
          'Skrini ya nje: makisio kwa density hiyohiyo.',
    ],
    displays: [
      _android(
        role: DisplayRole.inner,
        px: inner.$1,
        inch: inner.$2,
        ppi: inner.$3,
        refresh: inner.$4,
        type: 'OLED',
        sdkDpi: dpi,
        sdkProfile: sdk,
      ),
      _android(
        role: DisplayRole.outer,
        px: outer.$1,
        inch: outer.$2,
        ppi: outer.$3,
        refresh: outer.$4,
        type: 'OLED',
        estimateDpi: dpi,
      ),
    ],
  );
}
