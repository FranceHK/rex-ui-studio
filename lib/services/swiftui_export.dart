import '../models/ui_element.dart';
import 'export_common.dart';
import 'flutter_export.dart' show className;

/// Generates a SwiftUI view: a fixed-size ZStack with each element placed
/// at its design position.
String exportSwiftUI(DesignPage page) {
  final name = className(page.name).replaceAll(RegExp(r'Screen$'), 'View');
  final size = page.size;
  final usesPolygon = page.visibleElements.any(
    (e) => e.type.hasShape && shapePoints(e.shape) != null,
  );

  final b = StringBuffer()
    ..writeln('import SwiftUI')
    ..writeln()
    ..writeln(
      '/// ${page.device.name} (${fmt(size.width)}×${fmt(size.height)})'
      ' — generated by Rexa UI Studio',
    )
    ..writeln('struct $name: View {')
    ..writeln('    var body: some View {')
    ..writeln('        ZStack(alignment: .topLeading) {');
  for (final e in page.visibleElements) {
    final r = e.rect;
    b
      ..writeln('            ${_view(e)}')
      ..writeln(
        '                .frame(width: ${fmt(r.width)}, height: ${fmt(r.height)})',
      )
      ..writeln('                .offset(x: ${fmt(r.left)}, y: ${fmt(r.top)})');
  }
  b
    ..writeln('        }')
    ..writeln(
      '        .frame(width: ${fmt(size.width)}, height: ${fmt(size.height)}, '
      'alignment: .topLeading)',
    )
    ..writeln('        .background(${_color(page.background)})')
    ..writeln('    }')
    ..writeln('}');

  if (usesPolygon) {
    b
      ..writeln()
      ..writeln('/// A polygon through points given in a 0–1 unit square.')
      ..writeln('struct PolygonShape: Shape {')
      ..writeln('    let points: [CGPoint]')
      ..writeln()
      ..writeln('    func path(in rect: CGRect) -> Path {')
      ..writeln('        var path = Path()')
      ..writeln('        for (i, p) in points.enumerated() {')
      ..writeln(
        '            let point = CGPoint(x: rect.minX + p.x * rect.width, '
        'y: rect.minY + p.y * rect.height)',
      )
      ..writeln(
        '            if i == 0 { path.move(to: point) } '
        'else { path.addLine(to: point) }',
      )
      ..writeln('        }')
      ..writeln('        path.closeSubpath()')
      ..writeln('        return path')
      ..writeln('    }')
      ..writeln('}');
  }

  b
    ..writeln()
    ..writeln('#Preview {')
    ..writeln('    $name()')
    ..writeln('}');
  return b.toString();
}

String _view(UiElement e) {
  final text = _s(e.text);
  final font =
      '.font(.system(size: ${fmt(e.fontSize)}, '
      'weight: .${e.bold ? 'semibold' : 'regular'}))';
  final fg = '.foregroundStyle(${_color(e.textColor)})';
  final align = switch (e.effectiveTextAlign) {
    TextAlign.center => 'center',
    TextAlign.right || TextAlign.end => 'trailing',
    _ => 'leading',
  };

  return switch (e.type) {
    ElementType.text =>
      'Text("$text")$font$fg.frame(maxWidth: .infinity, '
          'maxHeight: .infinity, alignment: .$align)',
    ElementType.button =>
      'Button(action: {}) { Text("$text")$font$fg'
          '.frame(maxWidth: .infinity, maxHeight: .infinity) }'
          '.background(${_color(e.color)})'
          '.clipShape(RoundedRectangle(cornerRadius: ${fmt(e.radius)}))',
    ElementType.input =>
      'TextField("$text", text: .constant(""))$font'
          '.padding(.horizontal, 14)'
          '.overlay(RoundedRectangle(cornerRadius: ${fmt(e.radius)})'
          '.stroke(${_color(e.color)}))',
    ElementType.image =>
      '${_shape(e)}.fill(${_color(e.color)})'
          '.overlay(Image(systemName: "photo")'
          '.foregroundStyle(${_color(e.textColor)}))',
    ElementType.container => '${_shape(e)}.fill(${_color(e.color)})',
    ElementType.appBar =>
      'HStack(spacing: 16) { Image(systemName: "line.3.horizontal")$fg; '
          'Text("$text")$font$fg; Spacer() }'
          '.padding(.horizontal, 16).background(${_color(e.color)})',
    ElementType.navBar =>
      'HStack { ${[
            for (final (i, n) in const ['house', 'magnifyingglass', 'heart', 'person'].indexed) 'Spacer(); Image(systemName: "$n").foregroundStyle(${i == 0 ? _color(e.textColor) : _color(const Color(0xFF98A2B3))})',
          ].join('; ')}; Spacer() }'
          '.background(${_color(e.color)})',
    ElementType.iconItem =>
      'Image(systemName: "${sfSymbol(e.text)}").resizable().scaledToFit()'
          '.foregroundStyle(${_color(e.color)}) // ${e.text}',
    ElementType.avatar =>
      'Circle().fill(${_color(e.color)})'
          '.overlay(Text("$text")$font$fg)',
    ElementType.toggle =>
      'Toggle("", isOn: .constant(true)).labelsHidden()'
          '.tint(${_color(e.color)})',
    ElementType.divider =>
      'Rectangle().fill(${_color(e.color)}).frame(height: 1)'
          '.frame(maxHeight: .infinity)',
  };
}

String _shape(UiElement e) {
  if (shapePoints(e.shape) case final points?) {
    final list = points
        .map((p) => 'CGPoint(x: ${p.dx}, y: ${p.dy})')
        .join(', ');
    return 'PolygonShape(points: [$list])';
  }
  return switch (e.shape) {
    ElementShape.ellipse => 'Ellipse()',
    _ => 'RoundedRectangle(cornerRadius: ${fmt(e.radius)})',
  };
}

String _color(Color c) {
  final (r, g, b, a) = rgba(c);
  String f(double v) => ((v * 1000).round() / 1000).toString();
  return 'Color(red: ${f(r)}, green: ${f(g)}, blue: ${f(b)}'
      '${a < 1 ? ', opacity: ${f(a)}' : ''})';
}

String _s(String v) =>
    v.replaceAll(r'\', r'\\').replaceAll('"', r'\"').replaceAll('\n', r'\n');
