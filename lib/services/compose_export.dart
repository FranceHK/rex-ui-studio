import 'dart:ui';

import '../models/ui_element.dart';
import 'export_common.dart';
import 'flutter_export.dart' show className;

/// Generates a Jetpack Compose (Material 3) composable: a fixed-size Box
/// with each element offset to its design position.
String exportCompose(DesignPage page) {
  final name = className(page.name);
  final size = page.size;

  final b = StringBuffer()
    ..writeln('import androidx.compose.foundation.background')
    ..writeln('import androidx.compose.foundation.border')
    ..writeln('import androidx.compose.foundation.layout.*')
    ..writeln('import androidx.compose.foundation.shape.CircleShape')
    ..writeln('import androidx.compose.foundation.shape.GenericShape')
    ..writeln('import androidx.compose.foundation.shape.RoundedCornerShape')
    ..writeln('import androidx.compose.material.icons.Icons')
    ..writeln('import androidx.compose.material.icons.filled.*')
    ..writeln('import androidx.compose.material3.*')
    ..writeln('import androidx.compose.runtime.Composable')
    ..writeln('import androidx.compose.ui.Alignment')
    ..writeln('import androidx.compose.ui.Modifier')
    ..writeln('import androidx.compose.ui.geometry.Rect')
    ..writeln('import androidx.compose.ui.graphics.Color')
    ..writeln('import androidx.compose.ui.text.font.FontWeight')
    ..writeln('import androidx.compose.ui.text.style.TextAlign')
    ..writeln('import androidx.compose.ui.tooling.preview.Preview')
    ..writeln('import androidx.compose.ui.unit.dp')
    ..writeln('import androidx.compose.ui.unit.sp')
    ..writeln()
    ..writeln(
      '/** ${page.device.name} (${fmt(size.width)}×${fmt(size.height)})'
      ' — generated by Rexa UI Studio */',
    )
    ..writeln('@Composable')
    ..writeln('fun $name() {')
    ..writeln(
      '    Box(Modifier.size(${fmt(size.width)}.dp, ${fmt(size.height)}.dp)'
      '.background(${_color(page.background)})) {',
    );
  for (final e in page.elements) {
    final r = e.rect;
    final m =
        'Modifier.offset(${fmt(r.left)}.dp, ${fmt(r.top)}.dp)'
        '.size(${fmt(r.width)}.dp, ${fmt(r.height)}.dp)';
    b.writeln('        ${_composable(e, m)}');
  }
  b
    ..writeln('    }')
    ..writeln('}')
    ..writeln()
    ..writeln('@Preview')
    ..writeln('@Composable')
    ..writeln('private fun ${name}Preview() = $name()');
  return b.toString();
}

String _composable(UiElement e, String m) {
  final text = _s(e.text);
  final style =
      'color = ${_color(e.textColor)}, fontSize = ${fmt(e.fontSize)}.sp, '
      'fontWeight = FontWeight.${e.bold ? 'SemiBold' : 'Normal'}';
  final align = switch (e.effectiveTextAlign) {
    TextAlign.center => 'Center',
    TextAlign.right || TextAlign.end => 'End',
    _ => 'Start',
  };
  final rounded = 'RoundedCornerShape(${fmt(e.radius)}.dp)';

  return switch (e.type) {
    ElementType.text =>
      'Box($m, contentAlignment = Alignment.CenterStart) { '
          'Text("$text", $style, textAlign = TextAlign.$align, '
          'modifier = Modifier.fillMaxWidth()) }',
    ElementType.button =>
      'Button(onClick = {}, modifier = $m, shape = $rounded, '
          'colors = ButtonDefaults.buttonColors(containerColor = ${_color(e.color)})) '
          '{ Text("$text", $style) }',
    ElementType.input =>
      'OutlinedTextField(value = "", onValueChange = {}, '
          'placeholder = { Text("$text", $style) }, shape = $rounded, '
          'modifier = $m)',
    ElementType.image =>
      'Box($m.background(${_color(e.color)}, ${_shape(e)}), '
          'contentAlignment = Alignment.Center) '
          '{ Icon(Icons.Default.Image, contentDescription = null, '
          'tint = ${_color(e.textColor)}) }',
    ElementType.container =>
      'Box($m.background(${_color(e.color)}, ${_shape(e)}))',
    ElementType.appBar =>
      'Row($m.background(${_color(e.color)}).padding(horizontal = 16.dp), '
          'verticalAlignment = Alignment.CenterVertically) { '
          'Icon(Icons.Default.Menu, contentDescription = null, '
          'tint = ${_color(e.textColor)}); Spacer(Modifier.width(16.dp)); '
          'Text("$text", $style) }',
    ElementType.navBar =>
      'Row($m.background(${_color(e.color)}), '
          'horizontalArrangement = Arrangement.SpaceAround, '
          'verticalAlignment = Alignment.CenterVertically) { '
          '${[
            for (final (i, n) in const ['Home', 'Search', 'Favorite', 'Person'].indexed) 'Icon(Icons.Default.$n, contentDescription = null, tint = ${i == 0 ? _color(e.textColor) : _color(const Color(0xFF98A2B3))})',
          ].join('; ')} }',
    ElementType.iconItem =>
      'Icon(Icons.Default.${composeIcon(e.text)}, contentDescription = '
          '"${_s(e.text)}", tint = ${_color(e.color)}, modifier = $m)',
    ElementType.avatar =>
      'Box($m.background(${_color(e.color)}, CircleShape), '
          'contentAlignment = Alignment.Center) { Text("$text", $style) }',
    ElementType.toggle =>
      'Switch(checked = true, onCheckedChange = {}, modifier = $m, '
          'colors = SwitchDefaults.colors(checkedTrackColor = ${_color(e.color)}))',
    ElementType.divider =>
      'Box($m, contentAlignment = Alignment.Center) '
          '{ HorizontalDivider(color = ${_color(e.color)}) }',
  };
}

String _shape(UiElement e) {
  if (shapePoints(e.shape) case final points?) {
    final path = [
      for (final (i, p) in points.indexed)
        '${i == 0 ? 'moveTo' : 'lineTo'}(size.width * ${p.dx}f, '
            'size.height * ${p.dy}f)',
    ].join('; ');
    return 'GenericShape { size, _ -> $path; close() }';
  }
  return switch (e.shape) {
    ElementShape.ellipse => 'GenericShape { size, _ -> addOval(Rect(0f, 0f, size.width, size.height)) }',
    _ => 'RoundedCornerShape(${fmt(e.radius)}.dp)',
  };
}

String _color(Color c) =>
    'Color(0x${c.toARGB32().toRadixString(16).padLeft(8, '0').toUpperCase()})';

String _s(String v) => v
    .replaceAll(r'\', r'\\')
    .replaceAll('"', r'\"')
    .replaceAll(r'$', r'\$')
    .replaceAll('\n', r'\n');
